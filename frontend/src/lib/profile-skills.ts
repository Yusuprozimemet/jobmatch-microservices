export const PROFILE_SKILL_CATEGORIES = Object.keys(PROFILE_SKILLS_BY_CATEGORY);

export const PROFILE_SKILL_OPTIONS: ProfileSkillOption[] = Object.entries(
  PROFILE_SKILLS_BY_CATEGORY,
).flatMap(([category, values]) => values.map((value) => ({ category, value })));

export const PROFILE_SKILL_VALUES = new Set(
  PROFILE_SKILL_OPTIONS.map((skill) => skill.value),
);

