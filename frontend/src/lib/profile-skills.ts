export function normalizeProfileSkillsForCompatibility(skills: string[]) {
  return skills.reduce<string[]>((normalizedSkills, skill) => {
    const compatibleSkill = LEGACY_PROFILE_SKILL_VALUES[skill] ?? skill;

    if (!normalizedSkills.includes(compatibleSkill)) {
      normalizedSkills.push(compatibleSkill);
    }

    return normalizedSkills;
  }, []);
}

export function formatProfileSkillLabel(value: string) {
  if (SPECIAL_SKILL_LABELS[value]) {
    return SPECIAL_SKILL_LABELS[value];
  }

  return value
    .split("-")
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join(" ");
}
